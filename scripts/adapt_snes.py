"""Reproduce the browser SNES source from the two pinned GPL upstream checkouts.

Usage: python3 scripts/adapt_snes.py SNESTANG_CHECKOUT BOOT_ROM_CHECKOUT
No network access or HDL compiler is used. See examples/snes/upstream.json.
"""

import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "examples/snes"


def adapt(sources, boot):
    text = "// Generated by scripts/adapt_snes.py; distributed under GPL-3.0.\n"
    text += "// Provenance and exact source hashes: upstream.json.\n`ifndef VERILATOR\n`define VERILATOR\n`endif\n"
    for name, source in sources.items():
        if name.endswith(".vh"):
            continue
        for header, body in sources.items():
            if header.endswith(".vh"):
                source = source.replace(f'`include "{Path(header).name}"', body)
        source = re.sub(r"\bfunction\b(?!\s+automatic)", "function automatic", source)
        # Simulation-only printing is unavailable in the standalone Wasm ABI.
        source = re.sub(r"^\s*\$fdisplay\([^\n]*\);", ";", source, flags=re.M)
        if name == "src/SNES.v":
            source = source.replace(".HIGH_RES(),", ".HIGH_RES(HIGH_RES),")
            source = source.replace(".TURBO()", ".TURBO(1'b0)")
            source = source.replace("endmodule", "assign DBG_PPU_DAT=0; assign DBG_WRAM_DAT=0; assign PPU_DBG_BRK=0;\nendmodule")
        if name == "src/cpu.v":
            source = source.replace("endmodule", "assign DBG_CPU_BRK=0;\nendmodule")
        if name == "src/65C816/mcode.sv":
            # STATE2 is a combinational temporary, not an asynchronously reset FF.
            source = source.replace("reg [3:0] STATE2;", "")
            source = source.replace("STATE2 = STATE - 4'd1;", "")
            source = source.replace("STATE2[2:0]", "(STATE[2:0] - 3'd1)")
        if name == "src/dsp.v":
            source = source.replace(".IN_CLK(2147730)", ".IN_CLK(2147727)")
            source = source.replace("parameter ACLK_FREQ = 411904;", "parameter ACLK_FREQ = 409600;")
        if name == "src/ppu.v":
            # Match the two long dots in the original VHDL; the translated AND
            # condition can never be true. The short-line exception stays intact.
            source = source.replace("H_CNT == 323 && H_CNT == 327", "H_CNT == 323 || H_CNT == 327")
        if name == "src/smp.v":
            # Ship the independently authored GPL boot loader, not Sony ROM bytes.
            replacement = "localparam [7:0] IPLROM[0:63] = '{" + ",".join(f"8'h{b:02x}" for b in boot) + "};"
            source, count = re.subn(r"localparam \[7:0\] IPLROM\[0:63\] = '\{.*?\};", replacement, source, flags=re.S)
            assert count == 1
        text += f"\n// ---- upstream: {name} ----\n{source}\n"
    text += "`undef VERILATOR\n"
    return "\n".join(line.rstrip() for line in text.splitlines()) + "\n"


def main():
    snes, boot_root = map(Path, sys.argv[1:])
    manifest = json.loads((TARGET / "upstream.json").read_text())
    sources = {}
    for section, root in [("console", snes), ("boot", boot_root)]:
        for name, expected in manifest[section]["files"].items():
            data = (root / name).read_bytes()
            if hashlib.sha256(data).hexdigest() != expected:
                raise ValueError(f"Unexpected upstream contents: {name}")
            if section == "console" and name.startswith("src/"):
                sources[name] = data.decode()
    boot = (boot_root / "spc700-boot-rom.bin").read_bytes()
    assert len(boot) == 64
    (TARGET / "snes-core.v").write_text(adapt(sources, boot))
    (TARGET / "LICENSE").write_bytes((snes / "LICENSE").read_bytes())
    for name in manifest["boot"]["files"]:
        target = TARGET / "boot" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((boot_root / name).read_bytes())


if __name__ == "__main__":
    main()
