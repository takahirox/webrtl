"""Reproduce the browser SNES source from the two pinned GPL upstream checkouts.

Usage: python3 scripts/adapt_snes.py SNESTANG_CHECKOUT BOOT_ROM_CHECKOUT
No network access or HDL compiler is used. See examples/snes/upstream.json.
"""

import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "examples/snes"


def adapt(sources, boot):
    text = "// Generated by scripts/adapt_snes.py; distributed under GPL-3.0.\n"
    text += "// Provenance and exact source hashes: upstream.json.\n`ifndef VERILATOR\n`define VERILATOR\n`endif\n"
    for name, source in sources.items():
        if name.endswith(".vh"):
            continue
        for header, body in sources.items():
            if header.endswith(".vh"):
                source = source.replace(f'`include "{Path(header).name}"', body)
        source = re.sub(r"\bfunction\b(?!\s+automatic)", "function automatic", source)
        # Simulation-only printing is unavailable in the standalone Wasm ABI.
        source = re.sub(r"^\s*\$fdisplay\([^\n]*\);", ";", source, flags=re.M)
        if name == "src/SNES.v":
            # Invalid DMA A-bus reads supply zero even when PA selects WRAM
            # or a PPU register. CPU accesses keep their ordinary bus mux.
            source = source.replace("wire SMP_CE;", "wire DMA_A_INVALID;\nwire SMP_CE;")
            source = source.replace(".TURBO()", ".TURBO(), .DMA_A_INVALID(DMA_A_INVALID)")
            source = source.replace("assign BUSA_SEL =", "assign BUSA_SEL = DMA_A_INVALID ? 1'b1 :")
            source, count = re.subn(
                r"assign BUSA_DO =.*?;", "assign BUSA_DO = DMA_A_INVALID ? 8'h00 : DI;", source, flags=re.S)
            assert count == 1
            source = source.replace("wire SMP_WE_N;", "wire SMP_WE_N, SMP_RAM_WE_N;")
            source = source.replace(".WE_N(SMP_WE_N),", ".WE_N(SMP_WE_N), .RAM_WE_N(SMP_RAM_WE_N),")
            source = source.replace(".SMP_WE_N(SMP_WE_N),", ".SMP_WE_N(SMP_WE_N), .SMP_RAM_WE_N(SMP_RAM_WE_N),")
            source = source.replace(".HIGH_RES(),", ".HIGH_RES(HIGH_RES),")
            source = source.replace(".TURBO()", ".TURBO(1'b0)")
            source = source.replace("endmodule", "assign DBG_PPU_DAT=0; assign DBG_WRAM_DAT=0; assign PPU_DBG_BRK=0;\nendmodule")
        if name == "src/cpu.v":
            # bsnes/ares validA: both DMA directions and HDMA table/data
            # accesses exclude exactly these I/O ranges (including mirrors).
            source = source.replace("input TURBO,", "input TURBO,\n    output DMA_A_INVALID,")
            source = source.replace("assign DMA_ACTIVE = DMA_RUN | HDMA_RUN;", """assign DMA_ACTIVE = DMA_RUN | HDMA_RUN;
assign DMA_A_INVALID = DMA_ACTIVE && !INT_A[22] &&
    (INT_A[15:8] == 8'h21 ||      // $2100-$21ff
     INT_A[15:9] == 7'h20 ||      // $4000-$41ff
     INT_A[15:5] == 11'h210 ||    // $4200-$421f
     INT_A[15:7] == 9'h086);      // $4300-$437f""")
            # Suppress peripheral/cartridge side effects as well as reads.
            for strobe in ["CPURD_N", "CPUWR_N", "CPURD_CYC_N"]:
                source = re.sub(rf"({strobe} = )~((?:H)?DMA_A_(?:RD_CYC|RD|WR));",
                                rf"\1DMA_A_INVALID | ~\2;", source)
            # Standard pads do not drive the programmable I/O pins. Their
            # pull-ups read high when released, low when WRIO drives them low.
            source = source.replace("P65_DI = 8'h00;                                  //RDIO",
                                    "P65_DI = WRIO;                                   //RDIO (undriven pins pulled high)")
            source = source.replace("endmodule", "assign DBG_CPU_BRK=0;\nendmodule")
        if name == "src/swram.v":
            # Reverse WRAM-to-WRAM DMA writes the invalid B-bus read value
            # (zero) to A. Forward transfers still suppress the B write and
            # neither direction increments WMADD on a collision.
            source = source.replace("PA == 8'h80 && RAMSEL_N == 1'b0 ? 8'hFF : DI",
                                    "PA == 8'h80 && RAMSEL_N == 1'b0 ? 8'h00 : DI")
        if name == "src/65C816/mcode.sv":
            # STATE2 is a combinational temporary, not an asynchronously reset FF.
            source = source.replace("reg [3:0] STATE2;", "")
            source = source.replace("STATE2 = STATE - 4'd1;", "")
            source = source.replace("STATE2[2:0]", "(STATE[2:0] - 3'd1)")
        if name == "src/dsp.v":
            # TEST controls only SMP ARAM writes. Keep the raw SMP write
            # strobe for DSPADDR/DSPDATA, and leave DSP sample/echo slots alone.
            source = source.replace("    output SMP_CE,", "    input SMP_RAM_WE_N,\n    output SMP_CE,")
            source = source.replace("reg SMP_WE_N_buf;", "reg SMP_WE_N_buf, SMP_RAM_WE_N_buf;")
            source = source.replace("SMP_WE_N_buf <= SMP_WE_N;", "SMP_WE_N_buf <= SMP_WE_N;\n    SMP_RAM_WE_N_buf <= SMP_RAM_WE_N;")
            source = source.replace("RAM_WE = ~SMP_WE_N_buf;", "RAM_WE = ~SMP_RAM_WE_N_buf;")
            # I/O reads use the SMP register mux, but permitted writes also
            # reach backing ARAM (visible to DSP directory/sample accesses).
            source = source.replace("if (SMP_A_buf[15:4]== 12'h00F)",
                                    "if (SMP_A_buf[15:4]== 12'h00F && SMP_RAM_WE_N_buf)")
            # DSPADDR bit 7 selects read-only mirrors, including the special
            # KON/FLG/ENDX write paths outside the register RAM.
            source = source.replace("~SMP_WE_N && SMP_A == 16'h00F3 && SUBSTEP == 3 && CE",
                                    "~SMP_WE_N && !RI[7] && SMP_A == 16'h00F3 && SUBSTEP == 3 && CE")
            source = source.replace("SMP_EN_INT && SMP_A == 16'h00F3 && ~SMP_WE_N",
                                    "SMP_EN_INT && !RI[7] && SMP_A == 16'h00F3 && ~SMP_WE_N")
            # Previous-voice output is signed: a negative modulator reduces
            # pitch. A logical shift instead turns it into a positive value.
            source = source.replace("TOUT >> 5", "TOUT >>> 5")
            source = source.replace(".IN_CLK(2147730)", ".IN_CLK(2147727)")
            source = source.replace("parameter ACLK_FREQ = 411904;", "parameter ACLK_FREQ = 409600;")
            # The read pointer is latched before STEP 22. VS_ESA advances
            # ECHO_POS at STEP 29, between the two stereo writes; both writes
            # must still use the same latched address as the reads.
            source = source.replace("RAM_A = {TESA,8'h00} + ECHO_POS +",
                                    "RAM_A = ECHO_ADDR +")
            # BRR rounding applies to the combined negative product, not to
            # separately shifted positive terms. The difference feeds back
            # into every subsequent decoded sample.
            source = source.replace("(P0 >>> 1) - (P0 >>> 5)",
                                    "(P0 >>> 1) + ((-P0) >>> 5)")
            source = source.replace("+ P0 - (P0 >>> 6) - (P0 >>> 5)",
                                    "+ P0 + ((-P0 * 32'sd3) >>> 6)")
            source = source.replace("+ P0 - (P0 >>> 7) - (P0 >>> 5) - (P0 >>> 4)\n                    - P1 + (P1 >>> 4) + (P1 >>> 3)",
                                    "+ P0 + ((-P0 * 32'sd13) >>> 7)\n                    - P1 + ((P1 * 32'sd3) >>> 4)")
            source = source.replace("SR = (S << SCALE) >>> 1;",
                                    "if (SCALE <= 12) SR = (S << SCALE) >>> 1;\n                else SR = S & 16'hf800;", 1)
            # The DSP wraps the first three Gaussian terms to signed 16 bits
            # before adding the fourth and saturating (the hardware glitch).
            source = source.replace("GSUM = CLAMP16(SUM012 + SUM3);",
                                    "GSUM = CLAMP16(17'($signed(SUM012[15:0])) + SUM3);")
            # VS_VOLR merges the BRR end latch from VS_VOLL into ENDX_BUF.
            # Writing ENDX_BUF in VS_VOLL loses the event at that merge.
            source = source.replace("ENDX_BUF[VS.V] <= 1'b1;",
                                    "BRR_END[VS.V] <= 1'b1;")
            # echo_25 wraps tap 7 to signed 16 bits before adding it to the
            # wrapped taps 0-6 and saturating. In particular, +32768 is -32768.
            for channel in range(2):
                product = f"23'(signed'(ECHO_BUF[{channel}][FFC_CNT]) * ECHO_FFC[FFC_CNT]) >>> 6"
                source = source.replace(f"17'({product})",
                                        f"17'(shortint'({product}))")
        if name == "src/ppu.v":
            # WRIO.7 enables software counter capture; its falling edge still
            # captures independently, including when software reads are gated.
            source = source.replace(
                "if (~EXTLATCH && EXTLATCHr || ~PARD_N && PARD_Nr && PA == 8'h37)",
                "if ((~EXTLATCH && EXTLATCHr) || (EXTLATCH && ~PARD_N && PARD_Nr && PA == 8'h37))")
            # WBGLOG is a write-only register on the PPU1 open bus.
            source = source.replace("8'h24, 8'h25, 8'h26, 8'h28, 8'h29:",
                                    "8'h24, 8'h25, 8'h26, 8'h28, 8'h29, 8'h2A:")
            # CGRAM reads update PPU2 MDR; OAM reads update only PPU1 MDR.
            source = source.replace("PA == 8'h38 || PA == 8'h3C || PA == 8'h3D || PA == 8'h3F",
                                    "PA == 8'h3B || PA == 8'h3C || PA == 8'h3D || PA == 8'h3F")
            # Interlace halves the visible range, not the source tile height.
            # Preserve the full height mask for OBJ_TILE_ROW addressing.
            source = source.replace("reg [5:0] W, H, H2;", "reg [5:0] W, H, RANGE_H;")
            source, count = re.subn(r"if \(OBJINTERLACE\)\s+H = \{1'b0, H\[5:1\]\};\s+else\s+H2 = H;",
                                    """// Small rectangular objects use a 16-row source in interlace.
            if (OBJINTERLACE && !OAM_OBJ_S && OBJSIZE >= 3'd6)
                H = 6'd15;
            RANGE_H = OBJINTERLACE ? {1'b0, H[5:1]} : H;""", source)
            assert count == 1
            source = source.replace("(SCREEN_Y - OAM_OBJ_Y) <= {2'b0, H}",
                                    "(SCREEN_Y - OAM_OBJ_Y) <= {2'b0, RANGE_H}")
            # Flip the full source row including FIELD. Rectangular objects
            # flip each width-sized square independently, preserving the
            # section bit; using the height mask would exchange the sections.
            source, count = re.subn(
                r"if \(~OAM_OBJ_VFLIP\)\s+Y = SCREEN_Y - OAM_OBJ_Y;\s+else\s+"
                r"Y = ~\(SCREEN_Y - OAM_OBJ_Y\);\s+"
                r"if \(OBJINTERLACE\)\s+Y = \{Y\[6:0\], FIELD\};",
                """Y = SCREEN_Y - OAM_OBJ_Y;
                    if (OBJINTERLACE)
                        Y = {Y[6:0], FIELD};
                    if (OAM_OBJ_VFLIP)
                        Y = Y ^ {2'b00, W};""", source)
            assert count == 1
            # Negative nine-bit X wraps at 512 and can continue onto the left
            # edge. Only a tile on the visible right edge terminates fetching.
            source = source.replace("((TILE_X + 8) >= 256 && OAM_OBJ_X != 256)",
                                    "(!TILE_X[8] && (TILE_X + 9'd8) >= 9'd256 && OAM_OBJ_X != 9'd256)")
            # Each H-512 sample has its own transparency bits. DOT_CLK selects
            # the low sample; testing the high sample loses reversed stripes.
            for bg, old, new, zero in [(1, "7:4", "3:0", "4'b0000"),
                                       (2, "3:2", "1:0", "2'b00")]:
                for priority in [0, 1]:
                    source = source.replace(
                        f"BG{bg}_PIX_DATA[{old}] != {zero} && BGPR{priority}EN[{bg - 1}] && DOT_CLK",
                        f"BG{bg}_PIX_DATA[{new}] != {zero} && BGPR{priority}EN[{bg - 1}] && DOT_CLK")
            # Flipped screen coordinates are unsigned 255-X/Y, even though
            # the matrix multiplication consumes signed nine-bit operands.
            source = source.replace("9'(signed'(~M7_SCREEN_X[7:0]));    // signed extension",
                                    "{1'b0, ~M7_SCREEN_X[7:0]}; // unsigned 255-X")
            source = source.replace("9'(signed'(~MOSAIC_Y));            // signed extension",
                                    "{1'b0, ~MOSAIC_Y}; // unsigned 255-Y")
            # Match the two long dots in the original VHDL; the translated AND
            # condition can never be true. The short-line exception stays intact.
            source = source.replace("H_CNT == 323 && H_CNT == 327", "H_CNT == 323 || H_CNT == 327")
            # H-512's subscreen is the even (left) sample and main screen is
            # the odd sample. COLOR_OUT selects sub when DOT_CLK is high.
            source = source.replace("assign X_OUT = {OUT_X, DOT_CLK};",
                                    "assign X_OUT = {OUT_X, ~DOT_CLK};")
            # Inferred synchronous VRAM is sampled by SPR_GET_PIXEL at dot 16.
            # Advance Mode 7's coordinate after that sample, not at dot 15.
            source = re.sub(r"(parameter \[8:0\] M7_FETCH_START\s*= )9'b000001111;[^\n]*",
                            r"\g<1>9'd16; // 16", source)
            source = re.sub(r"(parameter \[8:0\] M7_FETCH_END\s*= )9'b100001110;[^\n]*",
                            r"\g<1>9'd271; // (16+256)-1=271", source)
            # Addition is halved before saturation. Clamping a six-bit sum
            # first incorrectly turns (31+15)/2 into full intensity.
            source = source.replace("if (temp[5])\n            temp = 6'b111111;",
                                    "if (temp[5] && !half)\n            temp = 6'b111111;")
        if name == "src/smp.v":
            # TEST writes require P=0 even when absolute addressing reaches
            # $00f0 with P=1. Expose the flag rather than infer it from A.
            source = source.replace("wire SPC700_CE;", """wire SPC700_CE;
wire SPC700_P, SPC700_IDLE;
reg [3:0] WAIT_CNT;
reg [5:0] TIMER_STEP;
wire INTERNAL_ACCESS;
wire [1:0] ACCESS_SPEED;
// One normal SMP slot is two reference clocks. Selections 2/3 use the
// documented deterministic 10/20-clock model; real silicon is unstable.
wire [3:0] ACCESS_SLOTS = ACCESS_SPEED == 0 ? 4'd1 :
                          ACCESS_SPEED == 1 ? 4'd2 :
                          ACCESS_SPEED == 2 ? 4'd5 : 4'd10;
wire ACCESS_READY = WAIT_CNT == ACCESS_SLOTS - 4'd1;""")
            source = source.replace("assign SPC700_CE = ENABLE & CE;", """assign INTERNAL_ACCESS = SPC700_IDLE || SPC700_A[15:4] == 12'h00f ||
                         (IPL_EN && SPC700_A >= 16'hffc0);
assign ACCESS_SPEED = INTERNAL_ACCESS ? CLK_SPEED : TM_SPEED;
assign SPC700_CE = ENABLE & CE & ACCESS_READY;
always @(posedge CLK) begin
    if (!RST_N) WAIT_CNT <= 0;
    else if (ENABLE && CE)
        WAIT_CNT <= ACCESS_READY ? 4'd0 : WAIT_CNT + 4'd1;
end""")
            source = source.replace(".RDY(SPC700_CE),", ".RDY(SPC700_CE),\n    .P_OUT(SPC700_P), .IDLE(SPC700_IDLE),")
            source = source.replace("CLK_SPEED <= 0;", "CLK_SPEED <= 0;\n        TEST <= 8'h0a;\n        TIMER_STEP <= 6'd3;")
            source = source.replace("4'h0: begin\n                            CLK_SPEED", "4'h0: if (!SPC700_P) begin\n                            TEST <= SPC700_D_OUT;\n                            CLK_SPEED")
            # Timers advance nominal 2/4/8/16 reference clocks per access,
            # independently of the CPU's anomalous 10/20-clock wait counts.
            # Latch the completed access selection before the CPU changes A.
            source = source.replace("TIMER_CE <= 1;", "TIMER_CE <= 1;\n            TIMER_STEP <= 6'd3 << ACCESS_SPEED;")
            source = source.replace("reg [4:0] TM_STEP;", "reg [5:0] TM_STEP;")
            source = source.replace("TM_STEP = (5'b00001 << CLK_SPEED) + (5'b00010 << TM_SPEED);", "TM_STEP = TIMER_STEP;")
            source = source.replace("reg [5:0] NEW_TM2_CNT;", "reg [6:0] NEW_TM2_CNT;")
            source = source.replace("NEW_TM2_CNT = TM2_CNT + TM_STEP;", "NEW_TM2_CNT = {1'b0, TM2_CNT} + {1'b0, TM_STEP};")
            source = source.replace("NEW_TM2_CNT[5:4] == 2'b11", "NEW_TM2_CNT >= 7'd48")
            source = source.replace("TM2_CNT <= NEW_TM2_CNT & 6'b001111;", "TM2_CNT <= 6'(NEW_TM2_CNT - 7'd48);")
            source = source.replace("TM2_CNT <= NEW_TM2_CNT;", "TM2_CNT <= NEW_TM2_CNT[5:0];")
            source = source.replace("    output WE_N,", "    output WE_N,\n    output RAM_WE_N,")
            source = source.replace("reg RAM_WRITE_EN;", "reg RAM_WRITE_EN, RAM_DISABLE;")
            source = source.replace("RAM_WRITE_EN <= 1;", "RAM_WRITE_EN <= 1;\n        RAM_DISABLE <= 0;")
            source = source.replace("RAM_WRITE_EN <= SPC700_D_OUT[1];",
                                    "RAM_WRITE_EN <= SPC700_D_OUT[1];\n                            RAM_DISABLE <= SPC700_D_OUT[2];")
            # I/O and the IPL overlay take precedence over disabled ARAM.
            source = source.replace("SPC700_D_IN = DI;\nend",
                                    "SPC700_D_IN = RAM_DISABLE ? 8'h5a : DI;\nend")
            source = source.replace("assign WE_N = SPC700_R_WN;",
                                    "assign WE_N = SPC700_R_WN | ~ACCESS_READY;\nassign RAM_WE_N = WE_N | ~RAM_WRITE_EN | RAM_DISABLE;")
            # Timer stage 2 is eight bits: target zero means 256 ticks.
            for timer in range(3):
                source = source.replace(f"T{timer}_CNT + 1 == T{timer}DIV",
                                        f"T{timer}_CNT + 8'd1 == T{timer}DIV")
            source, count = re.subn(r"4'hD:\s*\n                SPC700_D_IN",
                                   "4'h8, 4'h9:\n                SPC700_D_IN = AUX[SPC700_A[0]];\n            4'hD:\n                SPC700_D_IN", source)
            assert count == 1
            # Ship the independently authored GPL boot loader, not Sony ROM bytes.
            replacement = "localparam [7:0] IPLROM[0:63] = '{" + ",".join(f"8'h{b:02x}" for b in boot) + "};"
            source, count = re.subn(r"localparam \[7:0\] IPLROM\[0:63\] = '\{.*?\};", replacement, source, flags=re.S)
            assert count == 1
        if name == "src/spc700/spc700.v":
            source = source.replace("output reg WE_N,", "output reg WE_N,\n    output wire P_OUT,\n    output wire IDLE,")
            source = source.replace("assign EN =", "assign P_OUT = PSW[5];\nassign EN =")
            source = source.replace(".M(MC));", ".M(MC), .IDLE(IDLE));")
        if name == "src/spc700/mcode.v":
            # The upstream micro-operation annotations identify real bus
            # accesses. A held PC during an ALU/idle cycle is not a fetch.
            # Carry a separate bit alongside the unchanged microinstruction.
            source = source.replace("output SpcMCode_r M", "output reg IDLE,\n    output SpcMCode_r M")
            idle_bits = 0
            entries = re.findall(r"MCODE0\[(\d+)\]=\{([^\n]+?)\};([^\n]*)", source)
            assert len(entries) == 2048
            # Dummy PC reads consume external time even when their data is
            # unused (notably NOP). These facts follow the independent SPC700
            # instruction reference linked in docs/snes-fixtures.md; upstream
            # annotations omit them because the core discards their values.
            dummy_pc_reads = {
                0x00, 0x01, 0x06, 0x0d, 0x0f, 0x11, 0x19, 0x1c, 0x1d,
                0x20, 0x21, 0x26, 0x2d, 0x31, 0x39, 0x3c, 0x3d, 0x40,
                0x41, 0x46, 0x4d, 0x51, 0x59, 0x5c, 0x5d, 0x60, 0x61,
                0x66, 0x6d, 0x6f, 0x71, 0x79, 0x7c, 0x7d, 0x7f, 0x80,
                0x81, 0x86, 0x8e, 0x91, 0x99, 0x9c, 0x9d, 0x9e, 0x9f,
                0xa0, 0xa1, 0xa6, 0xae, 0xaf, 0xb1, 0xb9, 0xbc, 0xbd,
                0xbe, 0xbf, 0xc0, 0xc1, 0xc6, 0xce, 0xcf, 0xd1, 0xdc,
                0xdd, 0xdf, 0xe0, 0xe1, 0xe6, 0xed, 0xee, 0xef, 0xf1,
                0xfc, 0xfd, 0xfe, 0xff,
            }
            for index, value, annotation in entries:
                opcode, state = divmod(int(index), 8)
                access = state == 0 or bool(re.search(r"\[(PC|AX|SP|VECT)\]", annotation))
                access |= state == 1 and opcode in dummy_pc_reads
                idle_bits |= int(not access) << int(index)
            digits = f"{idle_bits:0512x}"
            table = "// Idle flags derived from upstream bus-access annotations.\nlocalparam [2047:0] IDLE_MAP = {\n"
            table += ",\n".join(f"    256'h{digits[i:i+64]}" for i in range(0, 512, 64)) + "\n};\n"
            source = source.replace("SpcMicroInst_r MI;", table + "\nSpcMicroInst_r MI;")
            # Latch the bit using precisely the same MUL/DIV lookup as MI.
            source = re.sub(r"MI <= MCODE0(\[[^;]+);", r"begin MI <= MCODE0\1; IDLE <= IDLE_MAP\1; end", source)
        if name == "src/spc700/muldiv.v":
            # Keep the existing nine shift/subtract steps. For Y >= 2*X,
            # divide YA-512*X by 256-X, then complement the quotient and add
            # X to the remainder (also defines division by zero). The shifted
            # divisor needs 17 bits to hold 256<<8 when X is zero.
            source = source.replace("reg [15:0] divt;", """reg [16:0] divt;
reg divOverflow, divV, divH;
reg [7:0] divX;""")
            source = source.replace("reg [15:0] remainder;", """reg [15:0] remainder;
wire [7:0] divQuotient = divOverflow ? ~quotient[7:0] : quotient[7:0];
wire [7:0] divRemainder = remainder[7:0] + (divOverflow ? divX : 8'd0);""")
            source = source.replace("divt <= {16{1'b0}};", """divt <= 17'b0;
      divOverflow <= 1'b0;
      divV <= 1'b0;
      divH <= 1'b0;
      divX <= 8'b0;""")
            source = source.replace("divt <= {1'b0,divt[15:1]};", "divt <= {1'b0,divt[16:1]};")
            source = source.replace("divt <= {X,8'b00000000};\n          remainder <= {Y,A};", """divOverflow <= {1'b0,Y} >= {X,1'b0};
          divV <= Y >= X;
          divH <= Y[3:0] >= X[3:0];
          divX <= X;
          if ({1'b0,Y} >= {X,1'b0}) begin
            divt <= (17'd256 - {9'b0,X}) << 8;
            remainder <= {Y,A} - {X,9'b0};
          end else begin
            divt <= {1'b0,X,8'b0};
            remainder <= {Y,A};
          end""")
            source = source.replace("tResult = {remainder[7:0],quotient[7:0]};", "tResult = {divRemainder,divQuotient};")
            source = source.replace("if(quotient[7:0] == 0)", "if(divQuotient == 0)")
            source = source.replace("tV = quotient[8];", "tV = divV;")
            source = source.replace("tS = quotient[7];", "tS = divQuotient[7];")
            source = source.replace("assign HO = Y[3:0] >= X[3:0] ? 1'b1 : 1'b0;", "assign HO = divH;")
        text += f"\n// ---- upstream: {name} ----\n{source}\n"
    text += "`undef VERILATOR\n"
    return "\n".join(line.rstrip() for line in text.splitlines()) + "\n"


def main():
    snes, boot_root = map(Path, sys.argv[1:])
    manifest = json.loads((TARGET / "upstream.json").read_text())
    sources = {}
    for section, root in [("console", snes), ("boot", boot_root)]:
        for name, expected in manifest[section]["files"].items():
            data = (root / name).read_bytes()
            if hashlib.sha256(data).hexdigest() != expected:
                raise ValueError(f"Unexpected upstream contents: {name}")
            if section == "console" and name.startswith("src/"):
                sources[name] = data.decode()
    boot = (boot_root / "spc700-boot-rom.bin").read_bytes()
    assert len(boot) == 64
    (TARGET / "snes-core.v").write_text(adapt(sources, boot))
    (TARGET / "LICENSE").write_bytes((snes / "LICENSE").read_bytes())
    for name in manifest["boot"]["files"]:
        target = TARGET / "boot" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((boot_root / name).read_bytes())


