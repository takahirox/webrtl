import argparse
from pathlib import Path


def source():
    program = [(0xD8, 'CLD; reset emulation mode has 8-bit A/X/Y')]

    def store(address, value, comment):
        program.extend([(0xA9, 'LDA immediate'), (value, comment),
                        (0x8D, f'STA ${address:04X}'),
                        (address & 255, 'address low'), (address >> 8, 'address high')])

    store(0x2100, 0x80, 'forced blank')
    store(0x2121, 0, 'CGRAM start')
    for index, color in enumerate([0x7C00, 0x001F, 0x03E0, 0x7FFF,
                                   0x0000, 0x03FF, 0x7FE0, 0x7C1F]):
        store(0x2122, color & 255, f'palette {index} low')
        store(0x2122, color >> 8, f'palette {index} high')
    store(0x2105, 0, 'Mode 0, BG1 8x8')
    store(0x2107, 4, 'map base $0400 words, 32x32')
    store(0x210B, 0, 'character base $0000 words')
    store(0x2115, 0x80, 'increment one word after high write')
    store(0x2116, 0, 'character address low')
    store(0x2117, 0, 'character address high')
    for tile in range(2):
        for row in range(8):
            low = 0x55 if tile == 0 else (0xFF if row % 2 == 0 else 0)
            high = (0xFF if row % 2 else 0) if tile == 0 else 0xFF
            store(0x2118, low, f'tile {tile} row {row} plane 0')
            store(0x2119, high, f'tile {tile} row {row} plane 1')
    store(0x2116, 0, 'map address low')
    store(0x2117, 4, 'map address high')
    store(0x2118, 0, 'map entry 0 low')
    store(0x2119, 0, 'map entry 0 high')
    store(0x2118, 1, 'map entry 1 low')
    store(0x2119, 4, 'map entry 1 high; palette 1')
    store(0x2100, 0x0F, 'display on, full brightness')
    program.append((0xDB, 'STP; scanout continues'))
    lines = ['// SPDX-License-Identifier: GPL-3.0-or-later',
             '// Original permitted program. Reproduce: python3 scripts/generate-bg1-rom.py',
             '// Generated bytes are intentionally editable in the browser.',
             'module bg1_rom (input [15:0] address, output reg [7:0] data);',
             '    always @* begin', '        case (address)']
    # Share case arms for repeated opcodes/address bytes; keep every immediate
    # byte individually labeled and editable without increasing source limits.
    fixed = {'LDA immediate', 'address low', 'address high'}
    groups = {}
    for i, (value, comment) in enumerate(program):
        if comment in fixed or comment.startswith('STA $'):
            groups.setdefault(value, []).append(0x8000 + i)
        else:
            lines.append(f"    16'h{0x8000 + i:04x}: data = 8'h{value:02x}; // {comment}")
    for value, addresses in groups.items():
        labels = ','.join(f"16'h{address:04x}" for address in addresses)
        lines.append(f"    {labels}: data = 8'h{value:02x};")
    lines.extend(["            16'hfffc: data = 8'h00; // reset vector low",
                  "            16'hfffd: data = 8'h80; // reset vector high",
                  "            default: data = 8'hdb; // STP", '        endcase',
                  '    end', 'endmodule', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / 'examples/cpu816-bg1/bg1-rom.v'
    if args.check:
        if path.read_text() != source():
            parser.exit(1, 'BG1 ROM differs from generator\n')
    else:
        path.write_text(source())
